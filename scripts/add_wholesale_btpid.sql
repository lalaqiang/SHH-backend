-- ============================================================
-- 添加批发业务类型到 tBas_BillType
-- BTPID = 00000000-0000-0000-0000-000000000010
-- 用于区分批发和零售数据（共用 tSal_Order / tStk_IO / tSal_Quote 表）
-- ============================================================

IF NOT EXISTS (SELECT 1 FROM tBas_BillType WHERE BTPID = '00000000-0000-0000-0000-000000000010')
BEGIN
    INSERT INTO tBas_BillType (
        BTPID, BTPCode, BTPName, InOut, Kind, Flg,
        CodePreFix, CodeRule, MaxCode, Note, PYCode,
        State, LUTime, EUser, EDate, AUser, ADate, SUser, SDate,
        btpSD, GridID, WorkFlowID, DefSQL, ShareAll
    ) VALUES (
        '00000000-0000-0000-0000-000000000010',
        '10', N'批发出货', -1, N'WS', N'Sys',
        N'WO', NULL, NULL, NULL, N'PFCH',
        N'S', GETDATE(), NULL, GETDATE(), NULL, NULL, NULL, NULL,
        N'1', NULL, NULL, NULL, N'Y'
    )
END
GO

-- 更新已有的批发订单 BTPID（根据单号前缀 WO 识别）
UPDATE tSal_Order SET BTPID = '00000000-0000-0000-0000-000000000010'
WHERE SoNo LIKE 'WO%' AND ISNULL(BTPID, '00000000-0000-0000-0000-000000000000') = '00000000-0000-0000-0000-000000000000'
GO

-- 更新已有的批发出库 BTPID（根据单号前缀 WI/SD 识别）
UPDATE tStk_IO SET BTPID = '00000000-0000-0000-0000-000000000010'
WHERE Kind = 'SD' AND IONo LIKE 'WI%' AND ISNULL(BTPID, '00000000-0000-0000-0000-000000000000') = '00000000-0000-0000-0000-000000000000'
GO

-- 更新已有的批发退货 BTPID
UPDATE tStk_IO SET BTPID = '00000000-0000-0000-0000-000000000010'
